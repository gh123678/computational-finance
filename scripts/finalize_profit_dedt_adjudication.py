def main():
    rl = pd.read_csv(AUDIT / 'auto_screen_20261008' / 'profit_dedt_screen_row_level.csv',
                     encoding='utf-8')
    diffs = rl[rl.status == 'value_differs_from_dated_original'].copy()
    diffs['abs_diff'] = (diffs.api_value - diffs.original_value).abs()
    diffs['pct_diff'] = diffs.abs_diff / diffs.original_value.abs() * 100

    rows = []
    for _, r in diffs.iterrows():
        key3 = (r.ts_code, r.ann_date, r.end_date)
        if key3 in ADJ:
            cat, note = ADJ[key3]
            # 603559 20191231 双行拆分行级裁决
            if key3 == ('603559.SH', 20200425, 20191231):
                if abs(r.api_value - 16324568.32) < 1:
                    cat, note = ADJ[key3]
                else:
                    cat, note = ADJ[('603559.SH', 20200425, 20191231, 'dup')]
        else:
            pct = r.pct_diff
            cat = 'true_diff_small' if pct < 1 else 'true_diff_large'
            note = NOTES.get(key3, '')
        rows.append(dict(row_sha256=r.row_sha256, ts_code=r.ts_code,
                         ann_date=r.ann_date, end_date=r.end_date,
                         api_value=r.api_value, original_value=r.original_value,
                         abs_diff=r.abs_diff, pct_diff=round(r.pct_diff, 4),
                         document_title=r.document_title, pdf_file=r.pdf_file,
                         adjudication=cat, note=note))
    out = pd.DataFrame(rows)
    out.to_csv(OUT / 'case_adjudication.csv', index=False, encoding='utf-8-sig')
    summ = out.adjudication.value_counts().to_dict()
    uniq = out.drop_duplicates(['ts_code', 'ann_date', 'end_date'])
    summ_unique = uniq.adjudication.value_counts().to_dict()
    result = dict(rows=len(out), by_category_rows=summ,
                  unique_keys=len(uniq), by_category_keys=summ_unique)
    (OUT / 'adjudication_summary.json').write_text(
        json.dumps(result, ensure_ascii=False, indent=1), encoding='utf-8')
    print(json.dumps(result, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main()
